// Explicit local smoke check; never reads production credentials.
import assert from 'node:assert/strict';
process.env.APP_BASE_URL = 'https://usage.example.test';
process.env.BIFROST_BASE_URL = 'http://127.0.0.1:4500';
process.env.BIFROST_ADMIN_USERNAME = 'test-admin';
process.env.BIFROST_ADMIN_PASSWORD = 'test-password';
process.env.ACCESS_TOKEN_ENCRYPTION_KEY = Buffer.alloc(32,1).toString('base64url');
process.env.SESSION_ENCRYPTION_KEY = Buffer.alloc(32,2).toString('base64url');
const { sealAccess } = await import('../src/lib/auth/tokens');
const base = 'http://127.0.0.1:3101';
const origin = 'https://usage.example.test';
assert.equal((await fetch(base+'/api/health')).status,200);
const token = await sealAccess({displayName:'Container test',virtualKeyId:'vk-a'},60);
const login = await fetch(base+'/api/auth/redeem',{method:'POST',headers:{Origin:origin,'Content-Type':'application/json'},body:JSON.stringify({token})});
assert.equal(login.status,200,await login.text());
const setCookie = login.headers.get('set-cookie')!;
assert.match(setCookie,/__Host-llm-usage-session=/);
assert.match(setCookie,/HttpOnly/); assert.match(setCookie,/Secure/); assert.match(setCookie,/SameSite=lax/i);
assert.equal(login.headers.get('cache-control'),'no-store');
const headers = { Cookie:setCookie.split(';')[0] };
const report = await fetch(base+'/api/dashboard/overview?from=2026-10-01&to=2026-10-02',{headers});
assert.equal(report.status,200);
const data = await report.json(); assert.equal(data.usage?.totals.cost,'0.125',JSON.stringify(data.analyticsError));
assert.equal(data.session.key.budgets[0].remaining,'9');
assert.doesNotMatch(JSON.stringify(data),/TEST-SECRET|TEST-PRIVATE-PROMPT|virtualKeyId|virtual_key_id/);
assert.equal((await fetch(base+'/api/dashboard/budget?virtualKeyId=vk-b',{headers})).status,400);
assert.equal((await fetch(base+'/api/auth/logout',{method:'POST',headers:{Origin:'https://evil.test',...headers}})).status,403);
const logout = await fetch(base+'/api/auth/logout',{method:'POST',headers:{Origin:origin,...headers}});
assert.match(logout.headers.get('set-cookie')!,/Max-Age=0/);
assert.equal((await fetch(base+'/api/dashboard/budget')).status,401);
console.log('Container smoke passed: health, Basic Auth reads, secure encrypted cookie, scoped report, DTO filtering, CSRF, logout.');
